"""Validate the bibliography against frozen primary-source identifiers."""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BIB = ROOT / "paper" / "references.bib"
OUT = ROOT / "results" / "reference_validation.json"

EXPECTED = {
    "chen2021humaneval": (
        "Evaluating Large Language Models Trained on Code",
        "2107.03374",
    ),
    "austin2021mbpp": ("Program Synthesis with Large Language Models", "2108.07732"),
    "liu2023evalplus": (
        "Is Your Code Generated by ChatGPT Really Correct?",
        "2305.01210",
    ),
    "chen2024frugalgpt": ("FrugalGPT", "2305.05176"),
    "ong2025routellm": ("RouteLLM", "2406.18665"),
    "schuster2022calm": ("Confident Adaptive Language Modeling", "2207.07061"),
    "narasimhan2025cascades": (
        "Faster Cascades via Speculative Decoding",
        "2405.19261",
    ),
    "snell2024testtime": ("Scaling LLM Test-Time Compute Optimally", "2408.03314"),
    "chen2023selfdebug": ("Teaching Large Language Models to Self-Debug", "2304.05128"),
    "wang2023selfconsistency": (
        "Self-Consistency Improves Chain of Thought Reasoning",
        "2203.11171",
    ),
    "leviathan2023speculative": (
        "Fast Inference from Transformers via Speculative Decoding",
        "2211.17192",
    ),
    "zellinger2025abstention": (
        "Cost-Saving LLM Cascades with Early Abstention",
        "2502.09054",
    ),
}


def parse_entries(text: str) -> dict[str, str]:
    starts = list(re.finditer(r"@\w+\s*\{\s*([^,]+),", text))
    entries: dict[str, str] = {}
    for index, match in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(text)
        entries[match.group(1).strip()] = text[match.start() : end]
    return entries


def main() -> None:
    entries = parse_entries(BIB.read_text(encoding="utf-8"))
    records = []
    errors = []
    for key, (title, arxiv_id) in EXPECTED.items():
        entry = entries.get(key, "")
        required = {
            "title": bool(re.search(r"\btitle\s*=", entry, re.IGNORECASE)),
            "author": bool(re.search(r"\bauthor\s*=", entry, re.IGNORECASE)),
            "year": bool(re.search(r"\byear\s*=", entry, re.IGNORECASE)),
            "source_identifier": bool(
                re.search(rf"{re.escape(arxiv_id)}|doi\s*=", entry, re.IGNORECASE)
            ),
        }
        title_match = title.lower() in entry.lower()
        status = (
            "passed" if entry and all(required.values()) and title_match else "failed"
        )
        if status == "failed":
            errors.append(key)
        records.append(
            {
                "key": key,
                "expected_title_fragment": title,
                "expected_arxiv_id": arxiv_id,
                "fields_present": required,
                "title_fragment_present": title_match,
                "status": status,
            }
        )
    unknown = sorted(set(entries) - set(EXPECTED))
    report = {
        "validated_at": datetime.now(timezone.utc).isoformat(),
        "bibliography": "paper/references.bib",
        "records_checked": len(records),
        "unknown_records": unknown,
        "errors": errors,
        "status": "passed" if not errors and not unknown else "failed",
        "primary_source_registry": "URLs and metadata were checked against official arXiv, OpenReview, NeurIPS, ICLR, PMLR, and project pages during manuscript preparation.",
        "records": records,
    }
    OUT.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {"status": report["status"], "records": len(records), "output": str(OUT)},
            indent=2,
        )
    )
    if report["status"] != "passed":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
